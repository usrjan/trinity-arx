// ============================================================
// ДВИЖОК ПЛАГИНА — МЕЙЕРОВСКИЙ СИНГЛТОН (Meyer's singleton)
// ============================================================
// Раньше движок жил в глобальном указателе `extern TrinityBuildEngine*
// g_engine`, который команды вручную new/delete-али в четырёх местах.
// Проблемы такой «утечки абстракции»:
//   1. Любой TU, включивший заголовок, получал доступ на ЗАПИСЬ к голому
//      указателю: утечки, двойное удаление и use-after-free висели только
//      на дисциплине программиста;
//   2. Владение было размазано по командам trinityStart/trinityStop;
//   3. Заголовок (публичный API модуля) не отражал реальную архитектуру:
//      движок в плагине ровно ОДИН — это инвариант, а не переменная.
// Синглтон возвращает единственный экземпляр по ссылке; время жизни ог-
// раничено выгрузкой DLL (статический объект уничтожается сам), состояние
// защищено от случайной подмены извне. Поток один (главный поток Auto-
// CAD), поэтому ленивая инициализация C++11 («magic static») потокобез-
// опасна без дополнительных блокировок. Экземпляр существует всегда;
// «запущен ли движок» отделяется методом isRunning() (соединение + та-
// ймер), а не null-указателем.
inline TrinityBuildEngine& engine() {
    static TrinityBuildEngine s_engine(TrinityConfig::load().basePath);
    return s_engine;
}

void trinityStart();
void trinityStop();
void trinityProcess();