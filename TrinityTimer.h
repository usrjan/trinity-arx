// TrinityTimer.h
//
// Безопасный таймер AutoCAD (ObjectARX).
//
// ПРОБЛЕМА, КОТОРУЮ РЕШАЕТ ЭТОТ ФАЙЛ:
// Запись в активный документ из колбэка Win32 SetTimer() без предварительного
// захвата document lock нарушает протокол блокировки документов AutoCAD.
// Колбэк SetTimer вызывается в произвольный момент message pump'а — в том
// числе когда пользователь уже начал команду, документ залочен другим
// приложением или идёт регенерация. Модификация БД в такой момент приводит
// к Access Violation / фатальному краху acad.exe.
//
// РЕШЕНИЕ (рекомендуемый Autodesk паттерн):
//   1. Windows-таймер заводится на окно AutoCAD (adsw_acadMainWnd()), чтобы
//      WM_TIMER приходил именно в его очередь сообщений (главный поток).
//   2. В колбэке ничего не делается напрямую — только postmessage на
//      пользовательское сообщение WM_TRINITY_TICK.
//   3. Обработчик WM_TRINITY_TICK выполняется на главном потоке AutoCAD,
//      где безопасно:
//        а) проверить acDocManager->isLockModeEnabled() и состояние
//           документа (eIsNotIdle / eIsBeingDestroyed — пропустить тик);
//        б) захватить write-lock целевого документа через
//           AcEditorReactor::lockDocument() с обязательным
//           unlockDocument() в деструкторе RAII-обёртки;
//        в) только после успешного лога выполнять работу с БД документа.
//   4. Если lock получить не удалось (другое приложение держит документ,
//      открыта модальная палитра и т.п.) — тик просто пропускается,
//      никакой записи в документ не происходит.
//
// Никаких изменений в других файлах не требуется: API совместим с
// SetTimer/KillTimer (возвращает non-zero id при успехе, 0 при отказе).
#pragma once

#include "StdAfx.h"

// Пользовательское сообщение «пришло время тика». PostMessage гарантирует,
// что обработчик выполнится на главном потоке AutoCAD вне контекста
// произвольного сообщения.
#define WM_TRINITY_TICK (WM_APP + 0x5401)

// Установка/снятие безопасного таймера.
// intervalMs — период, callback — вызывается ИЗ ОБРАБОТЧИКА WM_TRINITY_TICK
// на главном потоке AutoCAD, УЖЕ ПОСЛЕ успешного захвата write-lock
// активного документа. Возвращаемое значение совместимо с SetTimer:
// non-zero id при успехе, 0 при отказе.
UINT_PTR StartTrinityTimer(UINT intervalMs, void (*callback)());
void     StopTrinityTimer();

// Проверка, активен ли сейчас таймер (для команд статуса / отладки).
bool     IsTrinityTimerActive();
