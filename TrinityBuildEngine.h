// TrinityBuildEngine.h
#pragma once
#include "StdAfx.h"
#include "TrinityCore.h"
#include "TrinityFileManager.h"
#include <set>            // std::set — отслеживание активных кодов (защита от циклов графа)
#include <string>         // std::string — ключи/значения кэша и множеств
#include <unordered_map>  // std::unordered_map — m_builtCache (кэш собранных файлов)

class TrinityBuildEngine {
private:
    TrinityCore m_core;
    TrinityFileManager m_files;

    // ============================================================
    // КЭШ СОБРАННЫХ ФАЙЛОВ ЗА ОДИН ПРОХОД СБОРКИ
    // ============================================================
    // Проблема, которую решает кэш: один и тот же компонент (например,
    // типовой щит или планка) может входить в десятки конструкций одного
    // проекта. Без кэша ensureFileExists для каждого вхождения заново
    // загружал нейрон из MySQL и, если файл уже был на диске, выполнял
    // лишний _waccess. При глубоко вложенном графе это давало
    // ЭКСПОНЕНЦИАЛЬНЫЙ рост числа обращений к БД и диску (2^depth).
    //
    // Как работает: код -> путь к готовому DWG-файлу. Первая сборка
    // компонента кладёт результат в кэш; все последующие обращения к тому
    // же коду в рамках одной сборки (processAllProjects) завершаются
    // мгновенно, без БД и без проверок диска. Неудачные сборки в кэш НЕ
    // попадают (они могут быть временными) — они будут перебраны заново.
    //
    // Инвалидация: processAllProjects вызывает deleteProjectFiles(),
    // который физически удаляет DWG с диска, поэтому в начале обработки
    // КАЖДОГО проекта кэш полностью очищается (см. processAllProjects).
    // Иначе после удаления файлов кэш возвращал бы пути к несуществующим
    // файлам. Хранятся здесь только УСПЕШНЫЕ результаты — неудача может
    // быть временной (файл заблокирован, сетевая БД), её не кешируем.
    //
    // Потоки: движок вызывается только из главного потока AutoCAD
    // (trinityProcess по таймеру), конкуренции нет — мьютекс не нужен.
    // ============================================================
    std::unordered_map<std::string, std::string> m_builtCache;

    // ============================================================
    // МНОЖЕСТВО АКТИВНЫХ (ОБРАБАТЫВАЕМЫХ ПРЯМО СЕЙЧАС) КОДОВ
    // ============================================================
    // Защита от ЦИКЛОВ в графе связей (synapse): если проект A ссылается
    // на конструкцию B, а B (напрямую или через цепочку детей) — обратно
    // на A, рекурсия ensureFileExists уходила в бесконечную глубину до
    // срабатывания предохранителя depth > 20, попутно порождая повторные
    // сборки и дубли записей в БД. now-in / leave-out вокруг рекурсивного
    // спуска даёт O(log n)-проверку «этот код уже строится выше по стеку?»
    // и немедленный возврат пустой строки при обнаружении цикла.
    // Поведение строго стековое: элемент живёт ровно на время одного
    // вызова ensureFileExists и снимается во всех ветках выхода.
    // ============================================================
    std::set<std::string> m_activeCodes;

    // ============================================================
    // МНОЖЕСТВО КОДОВ, УДАЛЁННЫХ В ТЕКУЩЕМ ПРОХОДЕ deleteProjectFiles
    // ============================================================
    // Второй обход графа (рекурсивное удаление DWG перед сборкой) тоже
    // уязвим к циклам A -> B -> A: без «seen set» он был бы бесконечным.
    // В отличие от m_activeCodes здесь используется именно множество
    // ПОСЕЩЁННЫХ узлов прохода (не стека): повторное посещение узла в
    // рамках одной операции удаления бессмысленно (файл уже удалён),
    // поэтому узел обрабатывается строго один раз за проход. Множество
    // очищается автоматически по завершении верхнего уровня рекурсии
    // (см. флаг isTopLevel в реализации deleteProjectFiles).
    // ============================================================
    std::set<std::string> m_deletedCodes;

    // Примечание: вставка готового DWG проекта в текущий чертёж не
    // выполняется (ensureExists удалён как мёртвый код, реализованная
    // вместо него insertProjectToTarget вызывала ошибку 320 при работе
    // с активным документом и убрана). Результат сборки — файлы DWG
    // на диске; attachXref используется только внутри buildDwg для
    // вставки детей во временную базу.

    // Построить DWG конструкции/проекта из детей
    // Дети вставляются как XREF во временную базу,
    // потом wblock в чистую базу.
    // Примечание: повторные сборки общих детей исключаются кэшем
    // m_builtCache на уровне ensureFileExists — здесь кэш не нужен.
    //
    // Честность результата (защита от «ложного done»): сборка считается
    // успешной ТОЛЬКО если все дети обеспечены файлом и вставлены. Если
    // хоть один ребёнок не собран (нет нейрона по коду, цикл в графе,
    // ошибка геометрии/wblock/сохранения) или у проекта вообще нет детей,
    // возвращаем nullptr и удаляем неполный файл с диска — вызывающий код
    // увидит ошибку и переведёт проект в retry/error вместо markNeuronDone.
    AcDbDatabase* buildDwg(const TrinityNeuron& neuron, int depth);

    // Построить DWG детали (конечный уровень)
    // Геометрия → временная база → wblock → чистая база
    AcDbDatabase* buildDetail(const TrinityNeuron& detail);

    // Обеспечить существование файла детали/конструкции
    // Без вставки XREF. Возвращает путь к файлу.
    // Используется в buildDwg для рекурсивной подготовки детей.
    std::string ensureFileExists(const std::string& code, int depth = 0);

    // Рекурсивное удаление файлов проекта и всех его детей
    void deleteProjectFiles(const std::string& code);

    // ============================================================
    // ОБЩИЙ КОД processAllProjects()/processTick()
    // ============================================================
    // budgetMs < 0 — обрабатывать всю очередь без ограничения по вре-
    // мени; >= 0 — прерваться на границе проекта при исчерпании бюдже-
    // та (см. комментарии к processTick в публичной секции). Возвращает
    // число проектов, ВЗЯТЫХ из очереди в этом проходе (независимо от
    // успеха/провала каждого — статусы фиксирует БД).
    int processAllProjectsInternal(int budgetMs);

    // Гарантирует существование родительской директории файла (UTF-8 путь).
    // Нужен перед saveDwg: промежуточные папки могут отсутствовать,
    // а путь может содержать кириллицу (создаётся через _wmkdir).
    // Статическая утилита: не трогает состояние движка — только файл-
    // систему; вызывается и из buildDetail, и из buildDwg одинаково.
    static bool ensureDirectoryForFile(const std::string& filePathUtf8) {
        return TrinityFileManager::createDirectoryRecursiveA(
                   TrinityFileManager::parentDir(filePathUtf8));
    }

public:
    TrinityBuildEngine(const std::string& basePath) : m_files(basePath) {}

    bool init(const char* host, const char* user, const char* pass, const char* db) {
        // Новый сеанс работы по явной команде оператора (TRINITY_START):
        // сбрасываем купол доступности БД, чтобы подключение было попробо-
        // вано немедленно, без ожидания HALF-OPEN-интервала после возмож-
        // ного предыдущего «трипа».
        m_core.resetBreaker();
        return m_core.connect(host, user, pass, db);
    }

    void shutdown() {
        // Остановка по явной команде: принудительно открываем купол, что-
        // бы ни один «последний» тик, уже сидящий в очереди сообщений
        // AutoCAD, не ушёл в 5-секундный сетевой таймаут на мёртвом сер-
        // вере (UI защищён даже в гоночной ситуации stop-vs-tick).
        m_core.tripBreakerNow();
        m_core.disconnect();
        // Новый сеанс TRINITY_START должен видеть актуальное состояние
        // папок (файлы могли быть удалены/подменены вручную): сбрасываем
        // кэш собранных путей. Сами файлы НЕ удаляем — изменённая
        // логика сборки переиспользует всё, что уже есть в папке.
        m_builtCache.clear();
    }

    // Готов ли движок к работе: соединение с БД реально установлено
    // (после init()/connect() и до shutdown()/disconnect()). Команды
    // проверяют этот признак вместо старого `if (g_engine)` — синглтон
    // не бывает null, поэтому «запущено/не запущено» отделяется состоя-
    // нием ядра, а не указателя.
    bool isConnected() const { return m_core.isConnected(); }

    // Главный метод: обработать все pending-проекты
    int processAllProjects(AcDbDatabase* targetDb);

    // ============================================================
    // ТИК ТАЙМЕРА С БЮДЖЕТОМ ВРЕМЕНИ (защита UI от долгих сборок)
    // ============================================================
    // Проблема, которую решает бюджет: processAllProjects вызывается из
    // WM_TRINITY_TICK на ГЛАВНОМ потоке AutoCAD под write-lock активно-
    // го документа. Длинная сборка (сотни деталей) блокировала message
    // pump на десятки секунд — окна AutoCAD «не отвечают», курсор-песоч-
    // часы, невозможно прервать команду. Обрыв БД усугублял картину се-
    // тевыми таймаутами (от этого — купол в TrinityCore).
    //
    // Как работает: за один тик разрешено потратить не более kTickBudget-
    // Ms миллисекунд. По исчерпании бюджета обработка останавливается НА
    // ГРАНИЦЕ ПРОЕКТА (не внутри рекурсии!) — незавершённые проекты ос-
    // таются в 'pending'/'building' и будут продолжены следующим тиком
    // через 5 секунд. За счёт этого:
    //   - ни один тик не держит UI дольше ~200 мс + время одного проекта;
    //   - очередь полностью самоочищается за ceil(N/проектов_за_тик) тиков;
    //   - поведение идемпотентно: никаких промежуточных состояний «поло-
    //     винченного» проекта не возникает (проект либо собран целиком,
    //     либо честно помечен retry/error).
    //
    // Возвращает число проектов, реально обработанных этим тиком (для
    // решения вызывающего кода о необходимости acedUpdateDisplay()).
    int processTick(int budgetMs = kTickBudgetMs);

    // Бюджет одного тика, мс. 200 мс — порог «отзывчивости» Windows:
    // до него пользователь не воспринимает окно как зависшее. Сборка
    // одного крупного проекта может превысить бюджет — это допустимо
    // (проверка бюджета между проектами, не внутри них), но типичные
    // проекты укладываются целиком.
    static const int kTickBudgetMs = 200;

    // Диагностический доступ к ядру БД (команда TRINITY_STATUS печатает
    // состояние купола доступности; сам TrinityCore наружу не отдаётся).
    std::string dbBreakerState() const { return m_core.breakerState(); }
    int         dbFailureCount() const { return m_core.breaker().failureCount(); }
    int         dbBreakerTrips() const { return m_core.breaker().trips(); }
};